export type SyncEntity = keyof typeof syncEntities;
export function entityDefinition(entity: string) {
  if (!Object.hasOwn(syncEntities, entity))
    throw Error("허용하지 않은 동기화 자료입니다.");
  return syncEntities[entity as SyncEntity];
}
export function validatePublicRow(
  entity: SyncEntity,
  row: Record<string, unknown>,
) {
  const def = entityDefinition(entity);
  if (!row || typeof row !== "object" || Array.isArray(row))
    throw Error("자료 형식이 잘못되었습니다.");
  const allowed = new Set<string>(def.columns);
  if (Object.keys(row).some((k) => !allowed.has(k)))
    throw Error("자료에 허용되지 않은 필드가 있습니다.");
  if (def.keys.some((k) => row[k] === undefined || row[k] === null))
    throw Error("자료의 식별자가 없습니다.");
  return row;
}
export function projectSyncRow(
  entity: SyncEntity,
  row: Record<string, unknown>,
): Record<string, unknown> {
  const def = entityDefinition(entity),
    privateFields = new Set<string>(def.privateColumns);
  return validatePublicRow(
    entity,
    Object.fromEntries(
      Object.entries(row).filter(([k]) => !privateFields.has(k)),
    ),
  );
}
export function syncKey(
  entity: SyncEntity,
  row: Record<string, unknown>,
): string {
  const def = entityDefinition(entity);
  return JSON.stringify(
    def.keys.map((k) => {
      if (row[k] === undefined || row[k] === null)
        throw Error("자료의 식별자가 없습니다.");
      return String(row[k]);
    }),
  );
}
