import { beforeAll, afterAll, it, expect } from "vitest";
import { randomUUID } from "node:crypto";
import { testDatabase } from "./helpers/database";
import { createLibraryStore } from "../src/server/library-store";
import { createCurationStore } from "../src/server/curation-store";
import {
  exportCuration,
  curationMarkdown,
} from "../src/server/curation-export";
let fixture: Awaited<ReturnType<typeof testDatabase>>;
beforeAll(async () => {
  fixture = await testDatabase();
});
afterAll(async () => fixture?.pg.close());
async function setup(owner: string) {
  const library = createLibraryStore(fixture.db),
    store = createCurationStore(fixture.db);
  const note = await library.mutate(owner, {
    requestId: randomUUID(),
    type: "addNote",
    payload: {
      title: "감정",
      content: "감정을 인정한다. 책에서는 감정을 살피라고 한다.",
      kind: "thought",
    },
  });
  const run = await store.begin(owner, "scope-v1", "codex");
  const item = {
    id: randomUUID(),
    source: { kind: "note" as const, id: note.id!, version: "1" },
    kind: "tag" as const,
    proposedValue: "감정",
    evidence: { quote: "감정을 인정한다.", start: 0, end: 9 },
    coverage: "partial" as const,
    origin: "codex" as const,
    generator: "development-v1",
  };
  return { library, store, note, run, item };
}
it("keeps auxiliary tags separate from personal text and validates owner and source version", async () => {
  const { library, store, note, run, item } = await setup("a");
  const before = await library.snapshot("a");
  expect(await store.apply("a", run, [item])).toMatchObject({
    applied: 1,
    stale: 0,
    invalid: 0,
  });
  expect(await library.snapshot("a")).toEqual(before);
  expect(await store.apply("a", run, [item])).toMatchObject({ applied: 0 });
  const other = await store.begin("b", "scope", "codex");
  expect(
    await store.apply("b", other, [{ ...item, id: randomUUID() }]),
  ).toMatchObject({ invalid: 1 });
  await library.mutate("a", {
    requestId: randomUUID(),
    type: "editNote",
    payload: {
      id: note.id,
      expectedVersion: 1,
      title: "감정",
      content: "내가 수정한 생각",
      kind: "thought",
    },
  });
  expect(
    await store.apply("a", run, [
      { ...item, id: randomUUID(), proposedValue: "수용" },
    ]),
  ).toMatchObject({ stale: 1 });
});
it("rejects fabricated evidence and never fills an ISBN generated by AI", async () => {
  const { store, run, item, library } = await setup("evidence");
  expect(
    await store.apply("evidence", run, [
      { ...item, evidence: { quote: "존재하지 않는 근거", start: 0, end: 10 } },
    ]),
  ).toMatchObject({ invalid: 1 });
  expect(
    await store.apply("evidence", run, [
      {
        ...item,
        kind: "bibliography",
        proposedValue: { isbn: "9780000000002" },
      },
    ]),
  ).toMatchObject({ invalid: 1 });
  expect((await library.snapshot("evidence")).notes[0].content).toBe(
    "감정을 인정한다. 책에서는 감정을 살피라고 한다.",
  );
});
it("rejects detailed enrichment for metadata-only PDFs even with matching evidence", async () => {
  const { store, run, item, library } = await setup("paper-owner");
  const book = await library.mutate("paper-owner", {
    requestId: randomUUID(),
    type: "addBook",
    payload: { title: "상담 논문", formats: ["pdf"] },
  });
  await fixture.db.query(
    "UPDATE library_books SET source_data=$3 WHERE owner_id=$1 AND id=$2",
    ["paper-owner", book.id, JSON.stringify({ app: "Local PDF" })],
  );
  const docId = randomUUID();
  await fixture.db.query(
    "INSERT INTO library_documents(id,owner_id,book_id,root,path,relative_path,bytes,mtime_ns,processing_scope) VALUES($1,'paper-owner',$2,'root','paper.pdf','paper.pdf',1,'1','metadata_only')",
    [docId, book.id],
  );
  expect(
    await store.apply("paper-owner", run, [
      {
        ...item,
        source: { kind: "book", id: book.id!, version: "1" },
        kind: "description",
        proposedValue: "논문 상세 소개",
        evidence: { quote: "상담 논문" },
        coverage: "metadata",
      },
    ]),
  ).toMatchObject({ applied: 0, invalid: 1 });
});
it("rollback preserves user edits and hidden items cannot be resurrected", async () => {
  const { store, run, item } = await setup("rollback");
  await store.apply("rollback", run, [item]);
  await store.edit("rollback", item.id, 1, { value: "정서", state: "hidden" });
  expect(await store.rollback("rollback", run)).toEqual({
    reverted: 0,
    conflicted: 1,
  });
  const second = await store.begin("rollback", "scope2", "codex");
  expect(
    await store.apply("rollback", second, [{ ...item, id: randomUUID() }]),
  ).toMatchObject({ applied: 0 });
  const exported = await exportCuration(fixture.db, "rollback");
  expect(exported.items[0]).toMatchObject({
    origin: "codex",
    state: "hidden",
    reviewed_by: "human",
  });
  expect(
    exported.origins.some(
      (r: any) => r.origin === "ai" && r.reviewer === "human",
    ),
  ).toBe(true);
  expect(curationMarkdown(exported)).toContain("정서");
  expect(JSON.stringify(exported)).not.toContain("owner_id");
});
